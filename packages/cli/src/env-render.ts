// `.metistry/state/.env` is a DERIVED file (X-124; owner ruling 2026-10-04,
// "M7 reversed — a self-managing instance"): `metistry up` writes it from
// `.metistry/*.yaml` and the login Keychain, and nobody edits it by hand.
//
// This module is the pure half — what a rendered file looks like and how a
// hand edit is told from a render — so doctor can read a file without
// touching the Keychain, and the renderer (secrets.ts `renderEnvFile`) and
// every in-place writer share one definition of "stamped":
//
//   * The header. Fixed comment lines, then ONE line carrying the sha256 of
//     everything below it. `sh` sources comments without complaint (four
//     launchd jobs load the file with `set -a; . <file>`), and env.ts's
//     parser skips them, so the header costs nothing at runtime.
//   * The hash. Recomputed over the body and compared with the header's: a
//     mismatch is a hand edit (or a write by something that is not this
//     CLI). No header at all is a file written before the file was derived
//     — `pre-render` — which `up` migrates in passing.
//   * The record. `state/env-render.json` names every line the last render
//     wrote and a sha256 of each `NAME=value` — names and hashes, never a
//     value — so a hand edit can be reported LINE BY LINE (changed, added,
//     removed) rather than as "something differs". Derived state, 0600.
//
// Nothing here reads the Keychain, prints a value, or writes a file.

import { createHash } from "node:crypto";
import { join } from "node:path";

/** The comment lines every rendered `.env` opens with — fixed text, so two renders of the same inputs are byte-identical. */
export const ENV_RENDER_HEADER: readonly string[] = [
  "# GENERATED by `metistry up` from .metistry/*.yaml and the login Keychain — do not edit by hand.",
  "# A hand edit is detected by the hash below (`metistry doctor`, row `env`); `metistry up` derives the file",
  "# again and says what it did with each edited line. Secrets: `metistry secrets set|replace|mint`.",
];

/** The one line that makes the file verifiable: the sha256 of everything after it. */
export const ENV_HASH_PREFIX = "# metistry-env-sha256: ";

/** The previous `.env`, kept beside the first render (and beside a hand-edited one) for one release — 0600, deleted by nothing yet. */
export const PRE_RENDER_FILENAME = ".env.pre-render";

/** The render record: what the last render wrote, by name and line hash. Lives in the same `state/` directory as `.env`. */
export const RENDER_RECORD_FILENAME = "env-render.json";

const HASH_LINE = new RegExp(`^${ENV_HASH_PREFIX.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}([0-9a-f]{64})$`);
/** How far into the file the hash line may sit: the header is short, and a `# metistry-env-sha256:` buried in the body is a value, not a stamp. */
const HEADER_MAX_LINES = ENV_RENDER_HEADER.length + 2;

/** Where each line of the body came from, in the order the sections are written. */
export type EnvSection = "derived" | "keychain" | "carried";
export const ENV_SECTIONS: readonly EnvSection[] = ["derived", "keychain", "carried"];

export interface EnvRenderRecord {
  version: 1;
  /** the hash the header carried when this was written */
  sha256: string;
  /** every rendered name → sha256 of its `NAME=value` line, so a hand edit is named without storing a value */
  lines: Record<string, string>;
  /** which section each name was written in */
  sections: Record<EnvSection, string[]>;
  /** names whose previous `.env` value was NOT rendered because `.metistry/*.yaml` now says otherwise → where the rendered value came from */
  superseded: Record<string, string>;
}

export function sha256Hex(text: string): string {
  return createHash("sha256").update(text).digest("hex");
}

/** The hash of one assignment, as the record stores it. */
export function lineHash(name: string, value: string): string {
  return sha256Hex(`${name}=${value}`);
}

/**
 * Split a file into its stamp and its body. `present` is whether a hash
 * line sits where a render puts one; `body` is everything after it (the
 * whole file when there is none). The header's comment lines are not
 * compared — only the hash is load-bearing, so a later release may reword
 * the header without every install reading as hand-edited.
 */
export function splitEnvHeader(text: string): { present: boolean; sha256?: string; body: string } {
  const lines = text.split("\n");
  for (let i = 0; i < Math.min(lines.length, HEADER_MAX_LINES); i++) {
    const m = HASH_LINE.exec(lines[i]!);
    if (m) return { present: true, sha256: m[1]!, body: lines.slice(i + 1).join("\n") };
  }
  return { present: false, body: text };
}

/** The body with a fresh header and hash on top. Idempotent: stamping a stamped file replaces its stamp. */
export function stampEnv(text: string): string {
  const { body } = splitEnvHeader(text);
  return `${ENV_RENDER_HEADER.join("\n")}\n${ENV_HASH_PREFIX}${sha256Hex(body)}\n${body}`;
}

/**
 * What an in-place writer does to keep a rendered file consistent: when the
 * file it read was stamped, the file it writes is stamped again over the new
 * body; a file that was never rendered (`pre-render`) is left for `up` to
 * derive, header-less — so doctor's `pre-render` row stays true until the
 * migration has actually run, and a hand-written file never acquires a
 * stamp it did not earn.
 */
export function restampIfRendered(previous: string, next: string): string {
  return splitEnvHeader(previous).present ? stampEnv(next) : next;
}

export type EnvFileState =
  | { kind: "absent" }
  /** written by hand, or by a release before the file was derived: no stamp */
  | { kind: "pre-render" }
  /** stamped, and the body hashes to the stamp */
  | { kind: "rendered"; sha256: string }
  /** stamped, and the body does NOT hash to the stamp: something other than this CLI wrote it */
  | { kind: "hand-edited"; expected: string; actual: string };

/** Classify a file's text (undefined = no file). */
export function inspectEnvText(text: string | undefined): EnvFileState {
  if (text === undefined) return { kind: "absent" };
  const { present, sha256, body } = splitEnvHeader(text);
  if (!present) return { kind: "pre-render" };
  const actual = sha256Hex(body);
  return actual === sha256 ? { kind: "rendered", sha256: actual } : { kind: "hand-edited", expected: sha256!, actual };
}

export function renderRecordPath(stateDir: string): string {
  return join(stateDir, RENDER_RECORD_FILENAME);
}

export function preRenderPath(stateDir: string): string {
  return join(stateDir, PRE_RENDER_FILENAME);
}

/** Parse a record file's text; anything that is not a version-1 record is `undefined` (the file is derived state and is rewritten by the next render). */
export function parseRenderRecord(text: string | undefined): EnvRenderRecord | undefined {
  if (text === undefined) return undefined;
  let raw: unknown;
  try {
    raw = JSON.parse(text);
  } catch {
    return undefined;
  }
  if (!raw || typeof raw !== "object") return undefined;
  const r = raw as Partial<EnvRenderRecord>;
  if (r.version !== 1 || typeof r.sha256 !== "string" || !r.lines || typeof r.lines !== "object" || !r.sections || typeof r.sections !== "object") return undefined;
  const sections = Object.fromEntries(ENV_SECTIONS.map((s) => [s, Array.isArray((r.sections as Record<string, unknown>)[s]) ? ((r.sections as Record<string, unknown>)[s] as unknown[]).filter((n): n is string => typeof n === "string") : []])) as Record<EnvSection, string[]>;
  const lines = Object.fromEntries(Object.entries(r.lines).filter(([, v]) => typeof v === "string")) as Record<string, string>;
  const superseded = r.superseded && typeof r.superseded === "object" ? (Object.fromEntries(Object.entries(r.superseded).filter(([, v]) => typeof v === "string")) as Record<string, string>) : {};
  return { version: 1, sha256: r.sha256, lines, sections, superseded };
}

export interface EnvLineDiff {
  /** in the record and the file, with a different value */
  changed: string[];
  /** in the file, not in the record */
  added: string[];
  /** in the record, not in the file */
  removed: string[];
}

/**
 * The lines of `current` (the file's live assignments) against what the last
 * render wrote. Names only: the comparison is hash against hash.
 */
export function diffAgainstRecord(record: EnvRenderRecord, current: ReadonlyMap<string, string>): EnvLineDiff {
  const changed: string[] = [];
  const added: string[] = [];
  for (const [name, value] of [...current].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
    const was = record.lines[name];
    if (was === undefined) added.push(name);
    else if (was !== lineHash(name, value)) changed.push(name);
  }
  const removed = Object.keys(record.lines)
    .filter((n) => !current.has(n))
    .sort();
  return { changed, added, removed };
}

/** One sentence naming a diff, for a doctor row or an `up` note — never a value. */
export function describeLineDiff(d: EnvLineDiff): string {
  const parts: string[] = [];
  if (d.changed.length) parts.push(`changed ${d.changed.join(", ")}`);
  if (d.added.length) parts.push(`added ${d.added.join(", ")}`);
  if (d.removed.length) parts.push(`removed ${d.removed.join(", ")}`);
  return parts.length ? parts.join("; ") : "no assignment differs (a comment or blank line was edited)";
}

/**
 * The body of a rendered file: three sections in a fixed order, each sorted
 * by name, each omitted when empty. `lines` are complete `NAME=value` texts
 * — the caller decides quoting (a Keychain value is quoted for env.ts's
 * parser; a carried line keeps the right-hand side it had), so the file is
 * a function of its inputs and nothing else.
 */
export function composeEnvBody(sections: Record<EnvSection, string[]>, titles: Record<EnvSection, string>): string {
  const out: string[] = [];
  for (const s of ENV_SECTIONS) {
    const lines = sections[s];
    if (lines.length === 0) continue;
    out.push("", `# --- ${titles[s]} ---`, ...lines);
  }
  return out.length ? `${out.join("\n")}\n` : "\n";
}

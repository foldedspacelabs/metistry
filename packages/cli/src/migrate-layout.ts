// `metistry migrate-layout` — carry an existing instance from the legacy
// layout (vault in `Knowledge/`, config at the root) to the flat one (the
// instance directory IS the vault, machinery under `.metistry/`; owner's
// ruling 2026-09-17, docs/ops/instance-layout.md).
//
// Same shape as `migrate-inbox`: the shared StepRunner so `--dry-run` is the
// SAME code path with execution turned off, `git mv` for what git tracks and
// a plain move for what it does not, one commit at the end, and it restarts
// nothing — it prints the `metistry up` line and stops.
//
// THE PLAN IS BUILT BEFORE ANYTHING MOVES. `planMigration` only reads the
// filesystem; every refusal it can raise (a name collision at the root, a
// file collision inside `Inbox/`) is raised with the tree untouched, so a
// refused run is a no-op rather than a half-migrated instance. `--dry-run`
// prints exactly that plan.
//
// ORDER. The steps run in the order below, which differs from the order the
// ruling lists them in for one reason: a legacy root `inbox/` has to be
// normalised to `Inbox/` BEFORE `Knowledge/Inbox/` merges into it. macOS is
// case-insensitive, so with a lowercase `inbox/` at the root the merge target
// `Inbox/` "exists" and the merge would land the captures in a mis-cased
// directory that the reconciler's own casing rule (apps/reconciler/src/paths.ts
// PINNED_ROOTS) then refuses to write to.
//
//   1. preflight     a git repo, a legacy layout, a clean tree, nothing running
//   2. .metistry/    the config half moves under one dot-folder
//   3. state/        the derived half (gitignored, so a plain move)
//   4. Inbox/        the pre-#156 root `inbox/`, normalised and merged
//   5. vault         every entry of `Knowledge/` to the root; `Knowledge/` removed
//   6. .gitignore    rewritten to INSTANCE_GITIGNORE_LINES, user lines kept
//   7. database      one transaction; `Knowledge/` drops out of every stored path
//   8. .env          METISTRY_* values that spelled the old paths
//   9. commit        one commit, by the same author `init` and `migrate-inbox` use
//
// WHAT IT DOES NOT DO. launchd plists under `state/` are regenerated by
// `metistry up` from `ops/launchd/*.plist`, so this verb says so rather than
// editing generated files it does not own. It restarts nothing.

